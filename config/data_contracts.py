def _utf8_metadata(values: dict[str, str]) -> dict[bytes, bytes]:
    """将规范文本编码为 Arrow 要求的 UTF-8 字节 metadata。"""
    return {
        key.encode("utf-8"): value.encode("utf-8")  # encode 为字符串对象的方法
        for key, value in values.items()
    }



