@dataclass(frozen=True)  # frozen 要求生成的类实例是不可变
class DataFrameTypeMapping:
    """单个 Arrow 类型对应的 Pandas 与 Polars 类型。"""

    pandas_dtype: pd.ArrowDtype
    # pandas 0.23.0 起允许开发者定义自己的 dtype，只要继承
    # pandas.api.extensions.ExtensionDtype 并实现相应方法即可。
    # 其中内置的 ArrowDtype 为基于 Arrow 的通用类型

    polars_dtype: pl.DataType | type[pl.DataType]
    # pl.Int64 是一个类，继承自 pl.DataType
    # pl.Int64() 是 pl.DataType 的实例

    # type( pl.Int64  ): <class 'type'>
    # type( pl.Int64() ): <class 'polars.datatypes.classes.Int64'>

    # 实例化 面向 pl.Decimal(10, 2) 这种需要传参来定义的情况
    # 它与无需传参的如 pI.int64 的情况 一同被兼容为字段定义方式

    # type[pl.DataType] 为 Polars 数据类型的类本身
    # pl.DataType 为 Polars 数据类型实例

    # pl.DataType | type[pl.DataType] 告诉静态类型检查器（如 mypy、pyright）和 IDE
    # 参数同时被允许为类或类实例，防止被警告


def _type_mapping(
    arrow_type: pa.DataType,
    polars_dtype: pl.DataType | type[pl.DataType],
) -> DataFrameTypeMapping:
    """组合一个 Arrow 类型在 Pandas 和 Polars 中的对应类型。"""

    return DataFrameTypeMapping(pd.ArrowDtype(arrow_type), polars_dtype) # 注意直接传 pyarrow 的数据类型后转为 pd.ExtensionDtype
    # print( _type_mapping(pa.int64(), pl.Int64) )
    # DataFrameTypeMapping(pandas_dtype=<ArrowDtype: int64>, polars_dtype=<class 'polars.datatypes.classes.Int64'>)


ARROW_TYPE_MAPPINGS: dict[pa.DataType, DataFrameTypeMapping] = {
    pa.date32(): _type_mapping(pa.date32(), pl.Date),
    pa.timestamp("us", tz="UTC"): _type_mapping(pa.timestamp("us", tz="UTC"), pl.Datetime("us", "UTC")),
    pa.timestamp("us", tz="Asia/Shanghai"): _type_mapping(pa.timestamp("us", tz="Asia/Shanghai"), pl.Datetime("us", "Asia/Shanghai")),
    pa.time64("us"): _type_mapping(pa.time64("us"), pl.Time),
    pa.string(): _type_mapping(pa.string(), pl.String),
    pa.bool_(): _type_mapping(pa.bool_(), pl.Boolean),
    pa.int8(): _type_mapping(pa.int8(), pl.Int8),
    pa.int16(): _type_mapping(pa.int16(), pl.Int16),
    pa.int32(): _type_mapping(pa.int32(), pl.Int32),
    pa.int64(): _type_mapping(pa.int64(), pl.Int64),
    pa.float32(): _type_mapping(pa.float32(), pl.Float32),
    pa.float64(): _type_mapping(pa.float64(), pl.Float64),
}


def resolve_type_mapping(arrow_type: pa.DataType) -> DataFrameTypeMapping:
    """返回 Arrow 类型对应的 Pandas/Polars 类型。"""
    mapping = ARROW_TYPE_MAPPINGS.get(arrow_type)
    if mapping is not None: # 先查“固定类型字典”
        return mapping
    if pa.types.is_decimal128(arrow_type):  # 如果没查到，再判断它是不是需要动态构造映射的 Decimal 类型
        return _type_mapping(arrow_type, pl.Decimal(precision=arrow_type.precision, scale=arrow_type.scale))
    raise TypeError(f"Arrow 类型 {arrow_type} 尚未登记 Pandas/Polars 映射。")  # 两种情况都不符合时报错


def pandas_dtypes(schema: pa.Schema) -> dict[str, pd.ArrowDtype]:
    """按 Schema 字段顺序返回 Pandas 的 Arrow 扩展类型映射。"""
    return {field.name: resolve_type_mapping(field.type).pandas_dtype for field in schema}


def polars_dtypes(schema: pa.Schema) -> dict[str, pl.DataType | type[pl.DataType]]:
    """按 Schema 字段顺序返回 Polars 类型映射。"""
    return {field.name: resolve_type_mapping(field.type).polars_dtype for field in schema}


def _validate_columns(actual_columns: list[str], schema: pa.Schema) -> None:
    """要求实际列名及其顺序与 Schema 完全一致。"""
    if actual_columns != schema.names: # schema.names 是查看字段名的快捷方式，意味着 [field.name for field in schema]
        raise ValueError(f"数据列与 Schema 不一致。期望 {schema.names}，实际 {actual_columns}。")




def validate_arrow_table(table: pa.Table, schema: pa.Schema) -> pa.Table:
    """按权威 Schema 安全转换 Arrow 表，并校验列顺序和非空约束。"""

    if not isinstance(table, pa.Table):
        raise TypeError(f"期望 pyarrow.Table，实际为 {type(table).__name__}。")

    pandas_dtypes(schema) # 底层函数 resolve_type_mapping 会执行检查报错
    polars_dtypes(schema)
    _validate_columns(table.column_names, schema)

    # 把一个 PyArrow Table 的每一列转换成目标 schema 规定的类型，并拒绝可能丢失数据或产生错误的转换
    typed_table = table.cast(schema, safe=True) # safe=True 只允许 Arrow 认为安全的转换，否则抛出异常
    for field in schema:
        if not field.nullable and typed_table[field.name].null_count:
            raise ValueError(f"非空字段 {field.name!r} 包含空值。")
    return typed_table


def pandas_to_arrow(dataframe: pd.DataFrame, schema: pa.Schema) -> pa.Table:
    """将列及顺序匹配的 Pandas DataFrame 安全转换为契约化 Arrow 表。"""
    if not isinstance(dataframe, pd.DataFrame):
        raise TypeError(f"期望 pandas.DataFrame，实际为 {type(dataframe).__name__}。")
    _validate_columns(dataframe.columns.tolist(), schema)
    table = pa.Table.from_pandas(dataframe, schema=schema, preserve_index=False, safe=True)
    return validate_arrow_table(table, schema)


def polars_to_arrow(dataframe: pl.DataFrame, schema: pa.Schema) -> pa.Table:
    """将列及顺序匹配的 Polars DataFrame 安全转换为契约化 Arrow 表。"""
    if not isinstance(dataframe, pl.DataFrame):
        raise TypeError(f"期望 polars.DataFrame，实际为 {type(dataframe).__name__}。")
    _validate_columns(dataframe.columns, schema)
    table = dataframe.to_arrow()
    return validate_arrow_table(table, schema)


def arrow_to_pandas(table: pa.Table, schema: pa.Schema) -> pd.DataFrame:
    """校验 Arrow 表后转为 Pandas，并确认逐字段类型符合 Schema 映射。"""
    typed_table = validate_arrow_table(table, schema)
    dataframe = typed_table.to_pandas(types_mapper=pd.ArrowDtype)
    if dataframe.dtypes.to_dict() != pandas_dtypes(schema):
        raise TypeError("Pandas 类型与 Arrow Schema 映射不一致。")
    return dataframe


def arrow_to_polars(table: pa.Table, schema: pa.Schema) -> pl.DataFrame:
    """校验 Arrow 表后转为 Polars，并确认逐字段类型符合 Schema 映射。"""
    typed_table = validate_arrow_table(table, schema)
    dataframe = pl.from_arrow(typed_table, rechunk=True)
    if dict(dataframe.schema) != polars_dtypes(schema):
        raise TypeError("Polars 类型与 Arrow Schema 映射不一致。")
    return dataframe


def empty_pandas(schema: pa.Schema) -> pd.DataFrame:
    """创建具有指定 Schema 列和类型的空 Pandas DataFrame。"""
    return arrow_to_pandas(pa.Table.from_batches([], schema=schema), schema)


def empty_polars(schema: pa.Schema) -> pl.DataFrame:
    """创建具有指定 Schema 列和类型的空 Polars DataFrame。"""
    return arrow_to_polars(pa.Table.from_batches([], schema=schema), schema)
